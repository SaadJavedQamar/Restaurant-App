import React, { useState, useEffect } from 'react';
import { ArrowLeft, RotateCcw, Check, X, Flame, Trophy, HelpCircle } from 'lucide-react';
import { soundService } from '../../services/soundService';

interface FoodTriviaProps {
  onBack: () => void;
  isOrderReady?: boolean;
}

interface Question {
  question: string;
  options: string[];
  correctIndex: number;
  explanation: string;
}

const TRIVIA_QUESTIONS: Question[] = [
  {
    question: "What does the French culinary term 'Mise en place' mean?",
    options: ["Cooking in copper pans", "Everything in its place", "Flambéing with cognac", "Serving directly at table"],
    correctIndex: 1,
    explanation: "'Mise en place' refers to prepping and organizing all ingredients before cooking begins."
  },
  {
    question: "Which precious spice is harvested by hand from the stigma of crocus flowers?",
    options: ["Cardamom", "Star Anise", "Saffron", "Vanilla Bean"],
    correctIndex: 2,
    explanation: "Saffron requires roughly 75,000 flowers to yield a single pound, making it the world's most costly spice."
  },
  {
    question: "What traditional Italian pizza was created in 1889 to represent the Italian flag?",
    options: ["Quattro Formaggi", "Pizza Margherita", "Capricciosa", "Marinara"],
    correctIndex: 1,
    explanation: "Margherita uses basil (green), mozzarella (white), and tomatoes (red) matching the tricolor flag."
  },
  {
    question: "At what core internal temperature is a gourmet steak typically cooked to medium-rare?",
    options: ["110°F - 115°F", "130°F - 135°F", "155°F - 160°F", "175°F - 180°F"],
    correctIndex: 1,
    explanation: "130°F to 135°F delivers a warm red center with peak tenderness and natural juiciness."
  },
  {
    question: "What gives sourdough bread its signature tangy flavor and rustic crumb?",
    options: ["Baking soda reaction", "Wild yeast & lactobacilli fermentation", "Apple cider vinegar spray", "Extra mineral salt"],
    correctIndex: 1,
    explanation: "Lactic and acetic acids generated by symbiotic wild yeast starters create the rich sourdough flavor."
  },
  {
    question: "Which cheese is authentically used in traditional Roman Carbonara pasta?",
    options: ["Pecorino Romano", "Cheddar Sharp", "Gouda Smoked", "Mozzarella di Bufala"],
    correctIndex: 0,
    explanation: "Authentic Carbonara combines egg yolks, Guanciale, black pepper, and aged Pecorino Romano."
  }
];

export const FoodTriviaGame: React.FC<FoodTriviaProps> = ({ onBack, isOrderReady }) => {
  const [currentIndex, setCurrentIndex] = useState(0);
  const [selectedOption, setSelectedOption] = useState<number | null>(null);
  const [score, setScore] = useState(0);
  const [streak, setStreak] = useState(0);
  const [timer, setTimer] = useState(12);
  const [isFinished, setIsFinished] = useState(false);

  const currentQ = TRIVIA_QUESTIONS[currentIndex];

  // Countdown timer
  useEffect(() => {
    if (isFinished || selectedOption !== null || isOrderReady) return;

    if (timer <= 0) {
      handleAnswer(-1); // time ran out
      return;
    }

    const interval = setInterval(() => {
      setTimer(t => t - 1);
    }, 1000);

    return () => clearInterval(interval);
  }, [timer, isFinished, selectedOption, isOrderReady]);

  const handleAnswer = (optionIndex: number) => {
    if (selectedOption !== null || isFinished) return;
    setSelectedOption(optionIndex);

    const isCorrect = optionIndex === currentQ.correctIndex;
    if (isCorrect) {
      soundService.playEatSound();
      setScore(s => s + 100 + streak * 25);
      setStreak(st => st + 1);
    } else {
      soundService.playGameOverSound();
      setStreak(0);
    }
  };

  const nextQuestion = () => {
    if (currentIndex < TRIVIA_QUESTIONS.length - 1) {
      setCurrentIndex(i => i + 1);
      setSelectedOption(null);
      setTimer(12);
    } else {
      setIsFinished(true);
      soundService.playVictorySound();
    }
  };

  const restartQuiz = () => {
    setCurrentIndex(0);
    setSelectedOption(null);
    setScore(0);
    setStreak(0);
    setTimer(12);
    setIsFinished(false);
  };

  return (
    <div className="flex flex-col h-full max-w-md mx-auto p-4 select-none">
      {/* Top Header */}
      <div className="flex items-center justify-between pb-3">
        <button
          onClick={onBack}
          className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-slate-900 border border-slate-800 text-xs font-medium text-slate-300 hover:text-white"
        >
          <ArrowLeft className="w-3.5 h-3.5" />
          <span>Lobby</span>
        </button>

        <div className="flex items-center gap-3 text-xs">
          {streak > 1 && (
            <div className="flex items-center gap-1 text-orange-400 font-bold animate-pulse">
              <Flame className="w-3.5 h-3.5" />
              <span>{streak}x</span>
            </div>
          )}
          <div>
            <span className="text-slate-400">Score: </span>
            <span className="font-mono font-bold text-amber-400 tabular-nums">{score}</span>
          </div>
        </div>
      </div>

      {!isFinished ? (
        <div className="flex-1 flex flex-col justify-between py-2">
          {/* Progress & Timer */}
          <div>
            <div className="flex items-center justify-between text-xs text-slate-400 mb-1.5">
              <span>Question {currentIndex + 1} of {TRIVIA_QUESTIONS.length}</span>
              <span className={`font-mono font-bold ${timer <= 4 ? 'text-red-400 animate-pulse' : 'text-slate-300'}`}>
                {timer}s
              </span>
            </div>
            {/* Timer bar */}
            <div className="w-full h-1.5 bg-slate-800 rounded-full overflow-hidden">
              <div
                className={`h-full transition-all duration-1000 ${timer <= 4 ? 'bg-red-500' : 'bg-amber-400'}`}
                style={{ width: `${(timer / 12) * 100}%` }}
              />
            </div>

            {/* Question Card */}
            <div className="mt-4 rounded-2xl bg-slate-900 border border-slate-800 p-4 shadow-sm">
              <div className="flex items-start gap-2.5">
                <HelpCircle className="w-5 h-5 text-amber-400 shrink-0 mt-0.5" />
                <h3 className="text-sm font-semibold text-slate-100 leading-snug">
                  {currentQ.question}
                </h3>
              </div>
            </div>

            {/* Options */}
            <div className="mt-4 space-y-2.5">
              {currentQ.options.map((opt, idx) => {
                const isSelected = selectedOption === idx;
                const isCorrect = idx === currentQ.correctIndex;
                const hasAnswered = selectedOption !== null;

                let btnStyles = 'bg-slate-900/90 border-slate-800 text-slate-200 hover:border-slate-700';
                if (hasAnswered) {
                  if (isCorrect) {
                    btnStyles = 'bg-emerald-500/20 border-emerald-400 text-emerald-200';
                  } else if (isSelected) {
                    btnStyles = 'bg-red-500/20 border-red-400 text-red-200';
                  } else {
                    btnStyles = 'bg-slate-900/40 border-slate-900 text-slate-500';
                  }
                }

                return (
                  <button
                    key={idx}
                    onClick={() => handleAnswer(idx)}
                    disabled={hasAnswered}
                    className={`w-full min-h-[46px] px-4 py-2.5 rounded-xl border text-left text-xs font-medium flex items-center justify-between transition-colors ${btnStyles}`}
                  >
                    <span>{opt}</span>
                    {hasAnswered && isCorrect && <Check className="w-4 h-4 text-emerald-400 shrink-0" />}
                    {hasAnswered && isSelected && !isCorrect && <X className="w-4 h-4 text-red-400 shrink-0" />}
                  </button>
                );
              })}
            </div>

            {/* Fact Explanation */}
            {selectedOption !== null && (
              <div className="mt-3.5 rounded-xl bg-slate-900/60 border border-slate-800 p-3 text-[11px] text-slate-300">
                <strong className="text-amber-400 font-semibold block mb-0.5">Chef's Note:</strong>
                {currentQ.explanation}
              </div>
            )}
          </div>

          {/* Next Button */}
          {selectedOption !== null && (
            <div className="pt-3">
              <button
                onClick={nextQuestion}
                className="w-full h-11 rounded-xl bg-amber-500 hover:bg-amber-400 text-slate-950 font-semibold text-xs flex items-center justify-center transition-colors shadow-lg shadow-amber-500/10"
              >
                {currentIndex < TRIVIA_QUESTIONS.length - 1 ? 'Next Question' : 'View Results'}
              </button>
            </div>
          )}
        </div>
      ) : (
        /* Results View */
        <div className="flex-1 flex flex-col items-center justify-center text-center p-4">
          <div className="w-16 h-16 rounded-2xl bg-amber-500/10 border border-amber-500/30 flex items-center justify-center text-amber-400 mb-3">
            <Trophy className="w-8 h-8" />
          </div>
          <h3 className="text-lg font-bold text-white">Culinary Mastermind!</h3>
          <p className="text-xs text-slate-400 mt-1">You scored <strong className="text-amber-400">{score}</strong> points while waiting.</p>

          <button
            onClick={restartQuiz}
            className="mt-6 flex items-center gap-2 px-6 py-2.5 rounded-xl bg-amber-500 hover:bg-amber-400 text-slate-950 font-semibold text-xs shadow-lg transition-transform active:scale-95"
          >
            <RotateCcw className="w-4 h-4" />
            <span>Play Again</span>
          </button>
        </div>
      )}
    </div>
  );
};
